/** 작업 코드를 한글로 바꾼다. 표에 없으면 코드를 그대로 돌려준다. */
export function jobLabel(code: string): string {
  return JOB_LABEL[code] ?? code;
}

/** `TB_FCLT 12` 꼴의 대상에서 테이블 이름만 한글로 바꾼다. 표에 없으면 그대로 돌려준다. */
export function targetLabel(target: string): string {
  const [table = '', ...rest] = target.split(' ');
  const name = TABLE_LABEL[table];
  return name === undefined ? target : [name, ...rest].join(' ');
}
